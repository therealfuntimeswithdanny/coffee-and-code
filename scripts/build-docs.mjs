// Scans docs/ recursively for .md files and generates src/lib/docs.generated.ts
// so new docs are picked up automatically — no manual imports needed.
// The subfolder a doc lives in becomes its default sidebar section.
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const docsDir = fileURLToPath(new URL('../docs/', import.meta.url));
const outPath = fileURLToPath(new URL('../src/lib/docs.generated.ts', import.meta.url));

/** Recursively collects { rel, file } for every .md under dir (rel is posix-style). */
function collect(dir, prefix = '') {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...collect(join(dir, entry.name), rel));
    else if (entry.name.endsWith('.md')) out.push(rel);
  }
  return out;
}

const files = collect(docsDir);
const seen = new Set();

const imports = files.map((rel, i) => `import doc${i} from '../../docs/${rel}';`).join('\n');
const entries = files.map((rel, i) => {
  const parts = rel.split('/');
  const slug = parts[parts.length - 1].replace(/\.md$/, '');
  if (seen.has(slug)) throw new Error(`Duplicate docs slug "${slug}" (${rel}) — filenames must be unique across docs/.`);
  seen.add(slug);
  const folder = parts.slice(0, -1).join('/');
  return `  { slug: ${JSON.stringify(slug)}, folder: ${JSON.stringify(folder)}, markdown: doc${i} },`;
}).join('\n');

const output = `// Generated by scripts/build-docs.mjs — do not edit.
// Re-run via \`npm run build:docs\` (it also runs as part of dev/deploy).
${imports}

export interface RawDoc { slug: string; folder: string; markdown: string }

export const RAW_DOCS: RawDoc[] = [
${entries}
];
`;

writeFileSync(outPath, output);
console.log(`docs.generated.ts: ${files.length} doc(s) — ${files.join(', ') || 'none'}`);
